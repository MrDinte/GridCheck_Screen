#!/usr/bin/env python3
"""Signing for GridCheck firmware updates.

  sign.py sign   <private-key.pem> <firmware.bin> <out-app.bin>
      Appends a signature trailer: 64-byte ECDSA P-256 signature (r||s) of the
      SHA-256 of firmware.bin, then the 8 bytes "GCSIG001".
  sign.py verify <public-key.pem> <app.bin>
      Checks a signed file (what the screen does before switching to it).
  sign.py header <public-key.pem> <out.h>
      Writes the public key as a C array for the firmware (src/signing_pub.h).
  sign.py newkey <private-key.pem>
      Makes a new key pair (keep the private key secret; never commit it to a
      public repo). The public key goes next to it as *_pub.pem.

Screens only install updates signed with the private key that matches the
public key they were built with. Needs: pip install cryptography
"""
import hashlib
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature, encode_dss_signature)

MAGIC = b"GCSIG001"
TRAILER = 64 + len(MAGIC)


def load_private(path):
    return serialization.load_pem_private_key(open(path, "rb").read(), None)


def load_public(path):
    return serialization.load_pem_public_key(open(path, "rb").read())


def point(pub):
    return pub.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def sign(key_path, src, dst):
    key = load_private(key_path)
    data = open(src, "rb").read()
    if data[-TRAILER:][-len(MAGIC):] == MAGIC:
        sys.exit(f"{src} is already signed")
    r, s = decode_dss_signature(key.sign(data, ec.ECDSA(hashes.SHA256())))
    open(dst, "wb").write(data + r.to_bytes(32, "big") + s.to_bytes(32, "big") + MAGIC)
    print(f"signed {dst} (sha256 {hashlib.sha256(data).hexdigest()[:16]}...)")


def verify(pub_path, path):
    data = open(path, "rb").read()
    if len(data) <= TRAILER or data[-len(MAGIC):] != MAGIC:
        sys.exit("not signed")
    body, sig = data[:-TRAILER], data[-TRAILER:-len(MAGIC)]
    der = encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
    load_public(pub_path).verify(der, body, ec.ECDSA(hashes.SHA256()))  # raises if wrong
    print("signature OK")


def header(pub_path, out):
    p = point(load_public(pub_path))
    rows = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in p[i:i + 13]) for i in range(0, len(p), 13))
    open(out, "w").write(
        "// Public key that firmware updates must be signed with (ECDSA P-256, uncompressed point).\n"
        "// Generated by tools/sign.py header - safe to publish; it can only check signatures.\n"
        "#pragma once\n#include <cstdint>\n\n"
        f"static const uint8_t SIGNING_PUB[65] = {{\n{rows}}};\n")
    print(f"wrote {out}")


def newkey(path):
    key = ec.generate_private_key(ec.SECP256R1())
    open(path, "wb").write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                             serialization.NoEncryption()))
    pub = path.replace(".pem", "") + "_pub.pem"
    open(pub, "wb").write(key.public_key().public_bytes(serialization.Encoding.PEM,
                                                         serialization.PublicFormat.SubjectPublicKeyInfo))
    print(f"wrote {path} (secret) and {pub}")


if __name__ == "__main__":
    cmd, args = (sys.argv[1], sys.argv[2:]) if len(sys.argv) > 1 else ("", [])
    {"sign": sign, "verify": verify, "header": header, "newkey": newkey}.get(cmd, lambda *a: sys.exit(__doc__))(*args)
